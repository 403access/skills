  signalShares: report.signalShares,
  primaryMix: report.primaryMix,
  taskMulti: report.taskMulti,
  sizeBuckets: report.sizeBuckets,
  sessionShape: report.sessionShape,
  qualityImpact: report.qualityImpact,
  payloadImpact: report.payloadImpact,
  firstPromptOutcomes: report.firstPromptOutcomes,
